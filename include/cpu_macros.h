#ifndef CPU_MACROS_H
#define CPU_MACROS_H

// Max/min sizes
#define CPU_MEM_MAX_SIZE (256 * 256)
#define CPU_MEM_NUM_OPCODES 256
#define CPU_MEM_NUM_LEGAL_OPCODES 151

// Important memory locations
#define CPU_MEM_RESET_VEC_ADDR_H 0xFFFC
#define CPU_MEM_RESET_VEC_ADDR_L 0xFFFD
#define CPU_MEM_STACK_START 0x0100
#define CPU_MEM_STACK_END 0x01FF

// Flags
#define CPU_IS_READ 1
#define CPU_IS_WRITE 0

// Op codes

// Absolute addressing
// Read
#define CPU_OP_ORA_ABSOLUTE 0x0D
#define CPU_OP_BIT_ABSOLUTE 0x2C
#define CPU_OP_AND_ABSOLUTE 0x2D
#define CPU_OP_EOR_ABSOLUTE 0x4D
#define CPU_OP_ADC_ABSOLUTE 0x6D
#define CPU_OP_LDY_ABSOLUTE 0xAC
#define CPU_OP_LDA_ABSOLUTE 0xAD
#define CPU_OP_LDX_ABSOLUTE 0xAE
#define CPU_OP_CPY_ABSOLUTE 0xCC
#define CPU_OP_CMP_ABSOLUTE 0xCD
#define CPU_OP_CPX_ABSOLUTE 0xEC
#define CPU_OP_SBC_ABSOLUTE 0xED
// Read-Modify-Write
#define CPU_OP_ASL_ABSOLUTE 0x0E
#define CPU_OP_ROL_ABSOLUTE 0x2E
#define CPU_OP_LSR_ABSOLUTE 0x4E
#define CPU_OP_ROR_ABSOLUTE 0x6E
#define CPU_OP_DEC_ABSOLUTE 0xCE
#define CPU_OP_INC_ABSOLUTE 0xEE
// Write
#define CPU_OP_STY_ABSOLUTE 0x8C
#define CPU_OP_STA_ABSOLUTE 0x8D
#define CPU_OP_STX_ABSOLUTE 0x8E

// Zero-page addressing
// Read
#define CPU_OP_ORA_ZERO_PAGE 0x05
#define CPU_OP_BIT_ZERO_PAGE 0x24
#define CPU_OP_AND_ZERO_PAGE 0x25
#define CPU_OP_EOR_ZERO_PAGE 0x45
#define CPU_OP_ADC_ZERO_PAGE 0x65
#define CPU_OP_LDY_ZERO_PAGE 0xA4
#define CPU_OP_LDA_ZERO_PAGE 0xA5
#define CPU_OP_LDX_ZERO_PAGE 0xA6
#define CPU_OP_CPY_ZERO_PAGE 0xC4
#define CPU_OP_CMP_ZERO_PAGE 0xC5
#define CPU_OP_CPX_ZERO_PAGE 0xE4
#define CPU_OP_SBC_ZERO_PAGE 0xE5
// Read-Modify-Write
// Write

// Immediate addressing
#define CPU_OP_ORA_IMMEDIATE 0x09
#define CPU_OP_AND_IMMEDIATE 0x29
#define CPU_OP_EOR_IMMEDIATE 0x49
#define CPU_OP_ADC_IMMEDIATE 0x69
#define CPU_OP_LDY_IMMEDIATE 0xA0
#define CPU_OP_LDX_IMMEDIATE 0xA2
#define CPU_OP_LDA_IMMEDIATE 0xA9
#define CPU_OP_CPY_IMMEDIATE 0xC0
#define CPU_OP_CMP_IMMEDIATE 0xC9
#define CPU_OP_CPX_IMMEDIATE 0xE0
#define CPU_OP_SBC_IMMEDIATE 0xE9

// Implied addressing
#define CPU_OP_PHP_IMPLIED 0x08
#define CPU_OP_CLC_IMPLIED 0x18
#define CPU_OP_PLP_IMPLIED 0x28
#define CPU_OP_SEC_IMPLIED 0x38
#define CPU_OP_PHA_IMPLIED 0x48
#define CPU_OP_CLI_IMPLIED 0x58
#define CPU_OP_PLA_IMPLIED 0x68
#define CPU_OP_SEI_IMPLIED 0x78
#define CPU_OP_DEY_IMPLIED 0x88
#define CPU_OP_TXA_IMPLIED 0x8A
#define CPU_OP_TYA_IMPLIED 0x98
#define CPU_OP_TXS_IMPLIED 0x9A
#define CPU_OP_TAY_IMPLIED 0xA8
#define CPU_OP_TAX_IMPLIED 0xAA
#define CPU_OP_CLV_IMPLIED 0xB8
#define CPU_OP_TSX_IMPLIED 0xBA
#define CPU_OP_INY_IMPLIED 0xC8
#define CPU_OP_DEX_IMPLIED 0xCA
#define CPU_OP_CLD_IMPLIED 0xD8
#define CPU_OP_INX_IMPLIED 0xE8
#define CPU_OP_NOP_IMPLIED 0xEA
#define CPU_OP_SED_IMPLIED 0xF8

// Accumulator addressing
#define CPU_OP_ASL_ACCUMULATOR 0x0A
#define CPU_OP_ROL_ACCUMULATOR 0x2A
#define CPU_OP_LSR_ACCUMULATOR 0x4A
#define CPU_OP_ROR_ACCUMULATOR 0x6A

// Status register masks
#define CPU_FLAG_N (1 << 7)
#define CPU_FLAG_V (1 << 6)
#define CPU_FLAG_U (1 << 5)
#define CPU_FLAG_B (1 << 4)
#define CPU_FLAG_D (1 << 3)
#define CPU_FLAG_I (1 << 2)
#define CPU_FLAG_Z (1 << 1)
#define CPU_FLAG_C (1 << 0)

#endif // CPU_MACROS_H
